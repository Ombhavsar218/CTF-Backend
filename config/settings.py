def _env(name, default=None):
    """Read a setting from the environment, treating blank as unset."""
    value = os.environ.get(name)
    if value is None or not value.strip():
        return default
    return value.strip()


def _env_bool(name, default=False):
    raw = _env(name)
    if raw is None:
        return default
    return raw.lower() in {'1', 'true', 'yes', 'on'}


def _env_int(name, default):
    raw = _env(name)
    if raw is None:
        return default
    try:
        return int(raw)
    except ValueError:
        return default


def _env_float(name, default):
    raw = _env(name)
    if raw is None:
        return default
    try:
        return float(raw)
    except ValueError:
        return default


def _env_level(name, default):
    """Read a standard logging level, falling back on an invalid value."""
    raw = (_env(name) or default).upper()
    return raw if raw in {'DEBUG', 'INFO', 'WARNING', 'ERROR', 'CRITICAL'} else default


def _env_list(name, default=()):
    """Parse a comma-separated setting into a list of non-empty items."""
    raw = _env(name)
    if raw is None:
        return list(default)
    return [item.strip() for item in raw.split(',') if item.strip()]


def _env_path(name, default):
    """Resolve a filesystem setting, anchoring relative paths to BASE_DIR."""
    raw = _env(name)
    if raw is None:
        return default
    path = Path(raw)
    return path if path.is_absolute() else BASE_DIR / path


